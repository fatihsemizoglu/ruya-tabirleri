// Export helper function for template literals
export const t = (key: string, replacements?: Record<string, string | number>) => {
  const parts = key.split('.');
  const root = parts[0] as keyof typeof translations;
  let value: unknown = translations[root];

  for (let i = 1; i < parts.length; i++) {
    if (value && typeof value === 'object') {
      value = (value as Record<string, unknown>)[parts[i]];
    } else {
      value = undefined;
      break;
    }
  }

  if (typeof value === 'string' && replacements) {
    return Object.entries(replacements).reduce(
      (str, [k, val]) => str.replace(`{{${k}}}`, String(val)),
      value
    );
  }

  // Return the human-friendly Turkish value, fallback to a cleaned-up key
  // so that the UI never shows raw translation keys like "profile.newJournalBtn".
  if (typeof value === 'string') return value;
  // Try a nested lookup: if only the last segment is missing, return last segment
  // as a best-effort label (so e.g. "profile.unknownKey" -> "unknownKey" prettified)
  const last = parts[parts.length - 1];
  return last
    .replace(/([A-Z])/g, ' $1')
    .replace(/^./, (c) => c.toUpperCase())
    .trim();
};
