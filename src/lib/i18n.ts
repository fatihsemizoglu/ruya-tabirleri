export function t(key: string, locale: Locale = 'tr'): string {
  return translations[locale]?.[key] || translations['tr']?.[key] || key;
}

export function getLocaleFromPath(pathname: string): Locale {
  const match = pathname.match(/^\/(en|ar)(\/|$)/);
  return (match?.[1] as Locale) || 'tr';
}

export function getPathWithLocale(path: string, locale: Locale): string {
  const cleanPath = path.replace(/^\/(en|ar)/, '') || '/';
  if (locale === 'tr') return cleanPath;
  return `/${locale}${cleanPath}`;
}
