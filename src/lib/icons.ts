export function getIcon(iconName: string | null | undefined) {
  if (!iconName) return null;
  const normalized = iconName
    .charAt(0)
    .toUpperCase()
    .concat(iconName.slice(1))
    .replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
  return iconMap[normalized] || null;
}